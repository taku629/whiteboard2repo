"""Re-snap -> GitHub Pull Request.

Deterministic git + GitHub REST helper (no model calls). The generated repo is
kept as a local git working tree: the first build is committed on `main`
("board v1"), every Re-snap update is committed on its own branch. `open_pr`
pushes both to a dedicated GitHub repository and opens a Pull Request whose
body is the run's proof report: board diff, tests, mutation proof, coverage.

The token (GITHUB_TOKEN, fine-grained: Contents + Pull requests read/write on
one repo) is only used here. It is never passed to the model, written to job
files, or logged. Without a token, `open_pr` writes PR_PREVIEW.md instead.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

import httpx

AUTHOR = ["-c", "user.name=Whiteboard2Repo", "-c", "user.email=bot@whiteboard2repo.local"]
IGNORE = "__pycache__/\n.pytest_cache/\n*.db\n*.sqlite\n"


def _git(repo: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", *AUTHOR, *args], cwd=repo, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise RuntimeError(f"git {args[0]} failed: {_redact(r.stderr)[-400:]}")
    return r.stdout.strip()


def _redact(s: str) -> str:
    return re.sub(r"https://[^@\s]+@", "https://***@", s)


def snapshot(repo: Path, version: int, board_photo: Path | None, message: str, branch: str | None = None) -> str:
    """Commit the repo state for a board version. v1 goes on main, later versions on `branch`."""
    if not (repo / ".git").exists():
        _git(repo, "init", "-q", "-b", "main")
        (repo / ".gitignore").write_text(IGNORE)
    if branch:
        _git(repo, "checkout", "-q", "-B", branch)
    if board_photo and board_photo.exists():
        (repo / "board").mkdir(exist_ok=True)
        shutil.copy(board_photo, repo / "board" / f"v{version}.jpg")
    _git(repo, "add", "-A")
    if _git(repo, "status", "--porcelain"):
        _git(repo, "commit", "-q", "-m", message)
    return _git(repo, "rev-parse", "--short", "HEAD")


def ensure_baseline(repo: Path, board_photo: Path | None) -> None:
    """Called before an update: make sure the built v1 is committed on main."""
    if not (repo / ".git").exists():
        snapshot(repo, 1, board_photo, "Whiteboard2Repo: build from board v1")


def _proof_rows(proofs: list[dict[str, Any]]) -> str:
    rows = []
    for p in proofs:
        st = {True: "**KILLED** ✅", False: "SURVIVED ❌"}.get(p.get("caught"), "unknown ⚠️")
        mut = (p.get("mutation") or "").replace("|", "\\|").replace("\n", " ")
        mut = re.sub(r"\s*-?\s*FOR MUTATION TESTING.*$", "", mut)[:160]
        rows.append(f"| {p.get('invariant', '-')[:90]} | `{p.get('file', '-')}` | {mut} | {st} |")
    return "\n".join(rows) or "| (no new rules) | | | |"


def pr_body(report: dict[str, Any], owner_repo: str, branch: str) -> str:
    v = report["version"]
    raw = f"https://github.com/{owner_repo}/blob/{branch}/board"
    proofs = report.get("proofs", [])
    all_killed = bool(proofs) and all(p.get("caught") is True for p in proofs)
    tests = report.get("tests", {})
    status = "✅ tests green, every new rule proven" if tests.get("ok") and (all_killed or not proofs) else \
        "⚠️ NOT fully verified - see below before merging"
    cov = report.get("coverage", {})
    cov_lines = "\n".join(f"- {'✅' if i.get('ok') else '❌'} {i.get('kind')} **{i.get('name')}** → {i.get('where')}"
                          for i in cov.get("items", []))
    files = "\n".join(f"- `{f}`" for f in report.get("changed_files", [])) or "- (none)"
    return f"""## Whiteboard2Repo · Re-snap verification (board v{v-1} → v{v})

{status}

| Before (v{v-1}) | After (v{v}) |
|---|---|
| ![board v{v-1}]({raw}/v{v-1}.jpg?raw=true) | ![board v{v}]({raw}/v{v}.jpg?raw=true) |

### What changed on the board (read by Muse Spark Open)
{chr(10).join('- ' + s for s in report.get('summary', []))}

```mermaid
{report.get('mermaid', '').strip()}
```

### Tests
`pytest`: **{tests.get('passed', '?')} passed**, {tests.get('failed', 0)} failed (existing tests had to stay green).

### Mutation proof for new rules
The model deliberately broke the code that enforces each new rule in a throwaway copy; the rule's tests must go red.

| Rule | File | Mutation | Result |
|---|---|---|---|
{_proof_rows(proofs)}

### Board coverage: {cov.get('score', '?')}% (structural check)
{cov_lines}

### Files changed
{files}

---
Generated by [Whiteboard2Repo](https://github.com/taku629/whiteboard2repo) with Meta Muse Spark Open. Review before merging.
"""


def open_pr(job: Path, owner_repo: str, token: str | None) -> dict[str, Any]:
    repo = job / "repo"
    v = int((job / "version").read_text() or "1")
    if v < 2:
        raise RuntimeError("re-snap and apply an update first")
    report = json.loads((job / f"report.v{v}.json").read_text())
    branch = f"w2r/resnap-{job.name}-v{v}"
    body = pr_body(report, owner_repo, branch)
    if not token:
        (job / "PR_PREVIEW.md").write_text(body)
        return {"ok": False, "preview": True, "body": body,
                "detail": "GITHUB_TOKEN not set - wrote PR_PREVIEW.md instead"}
    remote = f"https://x-access-token:{token}@github.com/{owner_repo}.git"
    h = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"}
    with httpx.Client(timeout=30, headers=h) as gh:
        info = gh.get(f"https://api.github.com/repos/{owner_repo}")
        if info.status_code != 200:
            raise RuntimeError(f"cannot read {owner_repo} ({info.status_code})")
        base = info.json().get("default_branch") or "main"
        # publish the baseline only into an empty repo, never overwrite someone's main
        heads = gh.get(f"https://api.github.com/repos/{owner_repo}/branches").json()
        names = {b["name"] for b in heads} if isinstance(heads, list) else set()
        fresh = not names
        if names and base in names:
            # a just-created repo (one commit with only README/LICENSE/.gitignore) counts as empty
            commits = gh.get(f"https://api.github.com/repos/{owner_repo}/commits", params={"per_page": 2}).json()
            files = gh.get(f"https://api.github.com/repos/{owner_repo}/contents").json()
            fresh = len(commits) == 1 and isinstance(files, list) and \
                {f["name"].upper() for f in files} <= {"README.MD", "LICENSE", ".GITIGNORE"}
        elif names:
            raise RuntimeError("target repo has no default branch")
        published = _git(repo, "ls-remote", remote, "refs/tags/w2r-baseline-" + job.name, check=False)
        if fresh and not published:
            _git(repo, "push", "-q", "-f", remote, f"main:{base}")
            _git(repo, "tag", "-f", "w2r-baseline-" + job.name, "main")
            _git(repo, "push", "-q", remote, "w2r-baseline-" + job.name)
        elif not published:
            raise RuntimeError("target repo already has other history - use a dedicated, empty repo")
        _git(repo, "push", "-q", "-f", remote, f"{branch}:{branch}")
        r = gh.post(f"https://api.github.com/repos/{owner_repo}/pulls",
                    json={"title": f"Re-snap: board v{v-1} → v{v} ({', '.join(report.get('summary', [])[:2])[:120]})",
                          "head": branch, "base": base, "body": body})
        if r.status_code == 422 and "already exists" in r.text:
            prs = gh.get(f"https://api.github.com/repos/{owner_repo}/pulls",
                         params={"head": f"{owner_repo.split('/')[0]}:{branch}"}).json()
            if prs:
                return {"ok": True, "url": prs[0]["html_url"], "existing": True}
        if r.status_code >= 300:
            raise RuntimeError(f"PR create failed ({r.status_code}): {r.text[:200]}")
        return {"ok": True, "url": r.json()["html_url"], "number": r.json()["number"]}


def target_repo() -> str | None:
    return os.getenv("W2R_GITHUB_REPO")  # e.g. taku629/whiteboard2repo-demo
