"""Step 2 - deterministic skeleton.

Turns the architecture graph into a runnable baseline that is guaranteed to
pass its smoke tests *before* the agent touches it. The agent then only has
to add domain behaviour, which keeps the agent loop short and reliable.
"""
from __future__ import annotations

import json
import textwrap
from pathlib import Path
from typing import Any

from .vision import to_mermaid

CODE_KINDS = {"gateway", "service", "worker"}

COMMON_BUS = '''"""Event bus shared by all services.

Tests and local runs use the in-memory bus. Set BUS_URL=redis://... in
docker-compose to fan events out through Redis instead.
"""
from __future__ import annotations

import json
import os
from collections import defaultdict
from typing import Any, Callable

Handler = Callable[[dict[str, Any]], None]


class InMemoryBus:
    def __init__(self) -> None:
        self.handlers: dict[str, list[Handler]] = defaultdict(list)
        self.log: list[tuple[str, dict[str, Any]]] = []

    def subscribe(self, topic: str, handler: Handler) -> None:
        self.handlers[topic].append(handler)

    def publish(self, topic: str, payload: dict[str, Any]) -> None:
        self.log.append((topic, payload))
        for h in list(self.handlers[topic]):
            h(payload)


class RedisBus(InMemoryBus):  # pragma: no cover - exercised in docker-compose
    def __init__(self, url: str) -> None:
        super().__init__()
        import redis  # type: ignore
        self.r = redis.Redis.from_url(url)

    def publish(self, topic: str, payload: dict[str, Any]) -> None:
        super().publish(topic, payload)
        self.r.publish(topic, json.dumps(payload))


bus: InMemoryBus = RedisBus(os.environ["BUS_URL"]) if os.getenv("BUS_URL") else InMemoryBus()
'''

COMMON_DB = '''"""Database access shared by services (SQLAlchemy 2.x).

DATABASE_URL defaults to a local SQLite file; docker-compose points it at Postgres.
"""
from __future__ import annotations

import os

from sqlalchemy import create_engine
from sqlalchemy.orm import DeclarativeBase, sessionmaker
from sqlalchemy.pool import StaticPool

DATABASE_URL = os.getenv("DATABASE_URL", "sqlite://")

if DATABASE_URL.startswith("sqlite"):
    engine = create_engine(DATABASE_URL, connect_args={"check_same_thread": False},
                           poolclass=StaticPool)
else:  # pragma: no cover
    engine = create_engine(DATABASE_URL, pool_pre_ping=True)

SessionLocal = sessionmaker(bind=engine, expire_on_commit=False)


class Base(DeclarativeBase):
    pass


def init_db() -> None:
    Base.metadata.create_all(engine)


def reset_db() -> None:
    Base.metadata.drop_all(engine)
    Base.metadata.create_all(engine)
'''


def _service_app(c: dict[str, Any], graph: dict[str, Any]) -> str:
    outs = [e for e in graph["edges"] if e["from"] == c["id"]]
    ins = [e for e in graph["edges"] if e["to"] == c["id"]]
    doc = f'{c["label"]} ({c["kind"]}): {c.get("responsibility", "")}'.strip()
    wiring = "\n".join(f"#   -> {e['to']} via {e['protocol']} {e['label']!r}" for e in outs) or "#   (no outgoing edges)"
    wiring_in = "\n".join(f"#   <- {e['from']} via {e['protocol']} {e['label']!r}" for e in ins) or "#   (no incoming edges)"
    return (f'"""{doc}\n\nGenerated by Whiteboard2Repo from the whiteboard photo.\n"""\n'
            "from fastapi import FastAPI\n\n"
            "from common.bus import bus  # noqa: F401  (event edges)\n"
            "from common.db import init_db\n\n"
            f"# Wiring read from the board:\n{wiring}\n{wiring_in}\n\n"
            f'app = FastAPI(title="{c["label"]}")\n'
            "init_db()\n\n\n"
            '@app.get("/health")\n'
            "def health() -> dict:\n"
            f'    return {{"service": "{c["id"]}", "status": "ok"}}\n')


def _compose(graph: dict[str, Any]) -> str:
    lines = ["services:"]
    port = 8001
    deps_db = any(c["kind"] == "database" for c in graph["components"])
    deps_q = any(c["kind"] in ("queue", "cache") for c in graph["components"])
    for c in graph["components"]:
        if c["kind"] in CODE_KINDS:
            lines += [f"  {c['id']}:", "    build: .",
                      f"    command: uvicorn services.{c['id']}.app:app --host 0.0.0.0 --port 8000",
                      f"    ports: [\"{port}:8000\"]", "    environment:"]
            lines.append("      DATABASE_URL: postgresql+psycopg://app:app@db:5432/app" if deps_db
                         else "      DATABASE_URL: sqlite:////tmp/app.db")
            if deps_q:
                lines.append("      BUS_URL: redis://bus:6379/0")
            dep = [d for d, ok in (("db", deps_db), ("bus", deps_q)) if ok]
            if dep:
                lines.append(f"    depends_on: [{', '.join(dep)}]")
            port += 1
    if deps_db:
        lines += ["  db:", "    image: postgres:16-alpine",
                  "    environment: {POSTGRES_USER: app, POSTGRES_PASSWORD: app, POSTGRES_DB: app}",
                  "    ports: [\"5432:5432\"]"]
    if deps_q:
        lines += ["  bus:", "    image: redis:7-alpine", "    ports: [\"6379:6379\"]"]
    return "\n".join(lines) + "\n"


def build(graph: dict[str, Any], root: Path) -> list[str]:
    root.mkdir(parents=True, exist_ok=True)
    files: dict[str, str] = {}
    files["common/__init__.py"] = ""
    files["common/bus.py"] = COMMON_BUS
    files["common/db.py"] = COMMON_DB
    files["services/__init__.py"] = ""
    code = [c for c in graph["components"] if c["kind"] in CODE_KINDS]
    for c in code:
        files[f"services/{c['id']}/__init__.py"] = ""
        files[f"services/{c['id']}/app.py"] = _service_app(c, graph)
        files[f"tests/test_{c['id']}_health.py"] = textwrap.dedent(f'''\
            from fastapi.testclient import TestClient

            from services.{c['id']}.app import app


            def test_health():
                r = TestClient(app).get("/health")
                assert r.status_code == 200
                assert r.json()["service"] == "{c['id']}"
            ''')
    files["tests/__init__.py"] = ""
    files["conftest.py"] = textwrap.dedent('''\
        import os
        import sys

        sys.path.insert(0, os.path.dirname(__file__))
        os.environ.setdefault("DATABASE_URL", "sqlite://")
        ''')
    files["requirements.txt"] = "fastapi\nuvicorn\nsqlalchemy>=2\nhttpx\npytest\npsycopg[binary]\nredis\n"
    files["Dockerfile"] = ("FROM python:3.12-slim\nWORKDIR /app\nCOPY requirements.txt .\n"
                           "RUN pip install --no-cache-dir -r requirements.txt\nCOPY . .\n")
    files["docker-compose.yml"] = _compose(graph)
    files["board.json"] = json.dumps(graph, indent=2, ensure_ascii=False)
    inv = "\n".join(f"- {n.get('invariant') or n.get('text')}" for n in graph.get("notes", [])) or "- (none)"
    files["ARCHITECTURE.md"] = (f"# {graph['title']}\n\nGenerated from a whiteboard photo by Whiteboard2Repo "
                                f"(Meta Muse Spark Open{' + SAM 3.1' if graph.get('sam_grounded') else ''}).\n\n"
                                f"```mermaid\n{to_mermaid(graph)}\n```\n\n## Invariants from the board\n{inv}\n")
    for rel, content in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    return sorted(files)


def apply_diff(graph: dict[str, Any], root: Path, d: dict[str, Any]) -> dict[str, list[str]]:
    """Re-snap: update the skeleton in place for added/removed components.

    Existing service code is never overwritten; only new services get a fresh
    skeleton, removed services are deleted, and the board-level files
    (docker-compose.yml, board.json, ARCHITECTURE.md) are regenerated.
    """
    import shutil

    written: list[str] = []
    deleted: list[str] = []
    for c in d["components"]["added"]:
        if c["kind"] not in CODE_KINDS or (root / "services" / c["id"] / "app.py").exists():
            continue
        files = {
            f"services/{c['id']}/__init__.py": "",
            f"services/{c['id']}/app.py": _service_app(c, graph),
            f"tests/test_{c['id']}_health.py": textwrap.dedent(f'''\
                from fastapi.testclient import TestClient

                from services.{c['id']}.app import app


                def test_health():
                    r = TestClient(app).get("/health")
                    assert r.status_code == 200
                    assert r.json()["service"] == "{c['id']}"
                '''),
        }
        for rel, content in files.items():
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
            written.append(rel)
    for c in d["components"]["removed"]:
        sdir = root / "services" / c["id"]
        if sdir.exists():
            shutil.rmtree(sdir)
            deleted.append(f"services/{c['id']}/")
        for t in root.glob(f"tests/test_{c['id']}_*.py"):
            t.unlink()
            deleted.append(str(t.relative_to(root)))
    inv = "\n".join(f"- {n.get('invariant') or n.get('text')}" for n in graph.get("notes", [])) or "- (none)"
    board = {
        "docker-compose.yml": _compose(graph),
        "board.json": json.dumps(graph, indent=2, ensure_ascii=False),
        "ARCHITECTURE.md": (f"# {graph['title']}\n\nGenerated from a whiteboard photo by Whiteboard2Repo "
                            f"(Meta Muse Spark Open{' + SAM 3.1' if graph.get('sam_grounded') else ''}).\n\n"
                            f"```mermaid\n{to_mermaid(graph)}\n```\n\n## Invariants from the board\n{inv}\n"),
    }
    for rel, content in board.items():
        (root / rel).write_text(content)
        written.append(rel)
    return {"written": written, "deleted": deleted}
